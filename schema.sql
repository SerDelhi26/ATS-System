-- 1. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL DEFAULT 'Recruiter',
    joining_date DATE DEFAULT CURRENT_DATE,
    relieving_date DATE,
    qualification TEXT,
    experience_years INT DEFAULT 0,
    experience_months INT DEFAULT 0,
    status TEXT DEFAULT 'Active',
    password_hash TEXT NOT NULL,
    created_date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    modified_date TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. MASTER TABLES
CREATE TABLE IF NOT EXISTS public.company_master (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name TEXT UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.category_master (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.sub_category_master (
    sub_category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.category_master(category_id) ON DELETE CASCADE,
    sub_category_name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.job_title_master (
    job_title_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_title_name TEXT UNIQUE NOT NULL,
    status TEXT DEFAULT 'Active',
    created_date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    modified_date TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. JOB MANAGEMENT
CREATE TABLE IF NOT EXISTS public.job_management (
    job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_reference_no TEXT,
    job_title_id BIGINT REFERENCES public.job_title_master(job_title_id),
    company_id BIGINT REFERENCES public.company_master(company_id),
    category_id BIGINT REFERENCES public.category_master(category_id),
    sub_category_id BIGINT REFERENCES public.sub_category_master(sub_category_id),
    location TEXT,
    experience_min_year INT DEFAULT 0,
    experience_min_month INT DEFAULT 0,
    experience_max_year INT DEFAULT 0,
    experience_max_month INT DEFAULT 0,
    job_type TEXT DEFAULT 'Permanent',
    openings INT DEFAULT 1,
    pay_min NUMERIC,
    pay_max NUMERIC,
    currency TEXT DEFAULT 'INR',
    pay_unit TEXT DEFAULT 'Per Annum',
    skills_required TEXT,
    job_description TEXT,
    job_document_name TEXT,
    job_document_path TEXT,
    performa_invoice_no TEXT DEFAULT '',
    performa_invoice_status TEXT DEFAULT '',
    invoice_no TEXT DEFAULT '',
    invoice_status TEXT DEFAULT '',
    job_status TEXT DEFAULT 'Open',
    remark TEXT,
    created_by BIGINT,
    created_date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    modified_date TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. JOB ASSIGNMENT
CREATE TABLE IF NOT EXISTS public.job_assignment (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT REFERENCES public.job_management(job_id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES public.users(user_id) ON DELETE CASCADE,
    assigned_date TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. CANDIDATE MANAGEMENT
CREATE TABLE IF NOT EXISTS public.candidate_management (
    candidate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_reference_no TEXT,
    job_id BIGINT REFERENCES public.job_management(job_id) ON DELETE SET NULL,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    gender TEXT DEFAULT 'Not Specified',
    approx_dob DATE,
    email TEXT,
    mobile_no TEXT,
    alternate_mobile TEXT,
    current_location TEXT,
    experience_years INT DEFAULT 0,
    experience_months INT DEFAULT 0,
    current_company TEXT,
    current_designation TEXT,
    current_ctc NUMERIC,
    expected_ctc NUMERIC,
    notice_period TEXT,
    notice_negotiable TEXT DEFAULT 'No',
    skills TEXT,
    qualification TEXT,
    education_details TEXT,
    resume_name TEXT,
    resume_path TEXT,
    candidate_status TEXT DEFAULT 'Applied',
    current_stage TEXT DEFAULT 'Applied',
    remarks TEXT,
    created_by_user_id BIGINT,
    created_by_name TEXT,
    created_on TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_on TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. INTERVIEW MANAGEMENT
CREATE TABLE IF NOT EXISTS public.interview_management (
    interview_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT REFERENCES public.candidate_management(candidate_id) ON DELETE CASCADE,
    job_id BIGINT REFERENCES public.job_management(job_id) ON DELETE CASCADE,
    interview_round TEXT DEFAULT 'L1',
    interview_date DATE,
    interview_time TIME,
    interviewer_name TEXT,
    interview_mode TEXT DEFAULT 'MS Teams',
    interview_status TEXT DEFAULT 'Scheduled',
    feedback TEXT,
    remarks TEXT,
    created_by_user_id BIGINT,
    created_by_name TEXT,
    created_on TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. OFFER MANAGEMENT
CREATE TABLE IF NOT EXISTS public.offer_management (
    offer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT REFERENCES public.candidate_management(candidate_id) ON DELETE CASCADE,
    job_id BIGINT REFERENCES public.job_management(job_id) ON DELETE CASCADE,
    offered_ctc NUMERIC,
    joining_date DATE,
    offer_status TEXT DEFAULT 'Offered',
    remarks TEXT,
    created_by_user_id BIGINT,
    created_by_name TEXT,
    created_on TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

