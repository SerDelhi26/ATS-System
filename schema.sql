-- 9. TALENT MAPPING TABLE (Company-wise Hierarchy & Market Intelligence)
-- ====================================================================
CREATE TABLE IF NOT EXISTS public.talent_mapping (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_type TEXT NOT NULL DEFAULT 'Chemicals',     -- Seeds, Chemicals, Fertilizer, Agro-Chemicals, Others
    company_name TEXT NOT NULL,                         -- e.g. 'UPL', 'Tata Chemicals'
    candidate_name TEXT NOT NULL,                      -- e.g. 'Candidate A'
    designation TEXT NOT NULL,                         -- e.g. 'Head of Production'
    location TEXT,                                     -- e.g. 'Mumbai', 'Vapi'
    experience TEXT,                                   -- e.g. '12 Years' or '12'
    current_ctc NUMERIC,                               -- e.g. 3000000
    expected_ctc NUMERIC,                              -- Optional / nullable
    contact_number TEXT,                               -- e.g. '9876543210'
    email_id TEXT,                                     -- e.g. 'candidate.a@example.com'
    comments TEXT,                                     -- Recruiter remarks / notes
    reports_to_id BIGINT REFERENCES public.talent_mapping(mapping_id) ON DELETE SET NULL, -- Hierarchy link: Reports To
    candidate_id BIGINT REFERENCES public.candidate_management(candidate_id) ON DELETE SET NULL, -- Optional ATS profile link
    created_by BIGINT,
    created_by_name TEXT,
    created_on TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_on TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Indexing for fast search & hierarchy queries
